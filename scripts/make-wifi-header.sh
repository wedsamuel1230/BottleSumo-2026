#!/usr/bin/env bash
# Generate a sketch-local wifi_local.h from this machine's own Wi-Fi settings.
#
# The home network password is read from the macOS Keychain ("AirPort network
# password" item, the same one the Wi-Fi menu uses) and written straight into the
# gitignored header. It is never printed and never committed.
#
# Usage:
#   ./scripts/make-wifi-header.sh --ssid ChanNetwork
#   ./scripts/make-wifi-header.sh --ssid ChanNetwork --sketch bottlesumo_arduino
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
sketch="movement_test"
ssid=""

usage() {
  cat <<'EOF'
Write firmware/<sketch>/wifi_local.h from this machine's Wi-Fi keychain entry.

  --ssid NAME     network the robot joins (2.4 GHz); required when this Mac is
                  not on Wi-Fi right now
  --sketch NAME   sketch folder under firmware/ (default movement_test)
  -h, --help      this text

The home password is read with: security find-generic-password -wa "<ssid>"
It is written to the header and never printed. An existing OTA password in the
header is kept, so the Arduino IDE keeps offering the same port password.
EOF
}

for ((i = 1; i <= $#; i++)); do
  case "${!i}" in
    --ssid) next=$((i + 1)); ssid="${!next}" ;;
    --sketch) next=$((i + 1)); sketch="${!next}" ;;
    -h|--help) usage; exit 0 ;;
  esac
done

die() { echo "error: $*" >&2; exit 1; }

target_dir="${repo_root}/firmware/${sketch}"
[[ -d "$target_dir" ]] || die "no sketch folder: $target_dir"
target="${target_dir}/wifi_local.h"

if [[ -z "$ssid" ]]; then
  dev="$(networksetup -listallhardwareports | awk '/Hardware Port: (Wi-Fi|AirPort)/{getline; print $2; exit}')"
  if [[ -n "$dev" ]]; then
    ssid="$(networksetup -getairportnetwork "$dev" 2>/dev/null | sed -n 's/^Current Wi-Fi Network: //p')"
  fi
fi
[[ -n "$ssid" ]] || die "this Mac is not on Wi-Fi; pass --ssid <your 2.4 GHz network>"

case "$ssid" in
  *5G|*-5g|*5GHz) die "$ssid looks like a 5 GHz network; the ESP32-S3 radio is 2.4 GHz only" ;;
esac

password=""
if command -v security >/dev/null 2>&1; then
  password="$(security find-generic-password -wa "$ssid" 2>/dev/null || true)"
fi
if [[ -z "$password" ]]; then
  echo "warning: no Keychain item for \"$ssid\"; the header keeps an empty password" >&2
  echo "         (open Wi-Fi networks need none). Fix the file by hand otherwise." >&2
elif (( ${#password} < 8 || ${#password} > 63 )); then
  die "the Keychain password for \"$ssid\" is ${#password} characters; WPA2 needs 8-63"
fi

ota_password=""
if [[ -f "$target" ]]; then
  ota_password="$(sed -n 's/^#define OTA_PASSWORD  *"\(.*\)"$/\1/p' "$target" | head -1)"
fi
if [[ -z "$ota_password" ]]; then
  ota_password="$(LC_ALL=C tr -dc 'a-f0-9' < /dev/urandom | head -c 16)"
fi

old_umask="$(umask)"
umask 077
cat > "$target" <<EOF
// Generated by scripts/make-wifi-header.sh — gitignored, do not commit.
#pragma once

#define WIFI_SSID     "${ssid}"
#define WIFI_PASSWORD "${password}"

#define OTA_HOSTNAME  "bottlesumo-move"
#define OTA_PASSWORD  "${ota_password}"
EOF
umask "$old_umask"
chmod 600 "$target"

echo "wrote ${target#${repo_root}/}"
echo "  SSID          ${ssid}"
echo "  password      $([[ -n "$password" ]] && echo "read from Keychain (${#password} characters, not printed)" || echo "empty")"
echo "  OTA_PASSWORD  ${ota_password}"
echo
echo "Flash once over USB, then the Arduino IDE lists"
echo "  Tools > Port > \"bottlesumo-move at <ip> (network)\""
